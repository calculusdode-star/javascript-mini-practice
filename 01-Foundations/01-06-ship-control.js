const command = "Anchor";

switch(command){

    case "Start":
        console.log("Starting engines...");
        break;

    case "Stop":
        console.log("Stopping engines...");
        break;

    case "Anchor":
        console.log("Dropping anchor...");
        break;

    case "Dock":
        console.log("Docking procedure started...");
        break;

    default: 
       console.log("Unknown command");
}